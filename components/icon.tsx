export type IconName = keyof typeof ICONS;
/** 'duotone' adds a soft filled layer behind the outline (landing page feature icons). */
export type IconWeight = 'regular' | 'bold' | 'fill' | 'duotone';

const DEFAULT_WEIGHT: Partial<Record<IconName, IconWeight>> = {
  stop: 'fill',
  'check-circle': 'fill',
  'check-box': 'fill',
  'arrow-right-bold': 'bold',
};

export type IconProps = {
  name: IconName;
  size?: number;
  color?: string;
  weight?: IconWeight;
  /** Fill colour of the duotone layer; defaults to `color`. */
  duotoneColor?: string;
  /** Strength of the duotone layer (Phosphor default 0.2). */
  duotoneOpacity?: number;
  style?: StyleProp<ViewStyle>;
  accessibilityLabel?: string;
  accessibilityElementsHidden?: boolean;
  importantForAccessibility?: 'auto' | 'yes' | 'no' | 'no-hide-descendants';
};

export function Icon({
  name,
  size = 24,
  color,
  weight,
  importantForAccessibility,
  accessibilityElementsHidden,
  ...rest
}: IconProps) {
  const Glyph = ICONS[name];
  const hidden =
    accessibilityElementsHidden === true ||
    importantForAccessibility === 'no' ||
    importantForAccessibility === 'no-hide-descendants';
  const a11y =
    Platform.OS === 'web'
      ? hidden
        ? { 'aria-hidden': true }
        : {}
      : { importantForAccessibility, accessibilityElementsHidden };
  return <Glyph size={size} color={color} weight={weight ?? DEFAULT_WEIGHT[name] ?? 'regular'} {...a11y} {...rest} />;
}
